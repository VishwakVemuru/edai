"""Writes edai's runners/computer/stream_data.h format from a problems.json and its answers.json, so that edai's own
runner (run300.c and harness.c, unmodified) can solve and check any set of problems.
   python3 to_stream_data.py problems.json answers.json out/stream_data.h"""
import json, sys
P = json.load(open(sys.argv[1])); K = {a["id"]: a for a in json.load(open(sys.argv[2]))}
FAM = {"rule": 0, "trend": 1, "noise": 2}
rows = []
def ll(v): return ", ".join(f"{int(t)}LL" for t in v)
for p in P:
    k = K[p["id"]]; fam = FAM[k["family"]]
    if p["type"] == "sequence": kind, xs, ys, qs = 1, [0] * 16, p["terms"], [0, 0]
    else: kind, xs, ys, qs = 0, [e[0] for e in p["examples"]], [e[1] for e in p["examples"]], p["questions"]
    n = len(ys)
    truth = [0.0, 0.0] if fam == 2 else [float(v) for v in k["answer"]]
    tol = float(k.get("tolerance", 0.0)) if fam == 1 else 0.0
    xs = (list(xs) + [0] * 16)[:16]; ys = (list(ys) + [0] * 16)[:16]; qs = (list(qs) + [0, 0])[:2]
    rows.append(f"    {{ {kind}, {fam}, {n}, {{ {ll(xs)} }}, {{ {ll(ys)} }}, {{ {ll(qs)} }}, {{ {truth[0]!r}, {truth[1]!r} }}, {tol!r} }},")
open(sys.argv[3], "w").write(f"""/* generated by to_stream_data.py from {sys.argv[1].split('/')[-1]}: edai's runner format */
#ifndef STREAM_DATA_H
#define STREAM_DATA_H
#include <stdint.h>
#define N_PROBLEMS {len(rows)}
#define MAX_EXAMPLES 16
typedef struct {{ uint8_t kind; uint8_t family; uint8_t n; int64_t x[MAX_EXAMPLES]; int64_t y[MAX_EXAMPLES]; int64_t q[2]; double truth[2]; double tol; }} problem_t;
static const problem_t PROBLEMS[N_PROBLEMS] = {{
""" + "\n".join(rows) + "\n};\n#endif\n")
